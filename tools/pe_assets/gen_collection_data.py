"""Generate src/mods/pe_collection_data.h (PE repo) for the Collection mod (Bestiary + Wardrobe).

From findings/data/pe-bestiary-draft-2026-10-19.json: one Bestiary creature per base name (story
and Chrysler separately), its first-met stat block for display, its story section (prices from
findings/pe-skins-bestiary-design-2026-10-19.md), and the (map, enemy id) -> creature lookup for
every stat block (kills and Scan). Plus the skin catalogue with tiers.

    PYTHONPATH=tools python tools/pe_assets/gen_collection_data.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DRAFT = ROOT / 'findings/data/pe-bestiary-draft-2026-10-19.json'
OUT = Path('D:/Recomp Games/Parasite Eve Project/parasite-eve-recomp/src/mods/pe_collection_data.h')
ORDER = ['Day 1', 'Days 1-2', 'Day 2', 'Day 3', 'Day 4', 'Days 4-5', 'Day 6', 'late addition', 'special scene', 'Chrysler (EX)']
# section -> (weaknesses tier price, loot tier price) in Junk
PRICES = {'Day 1': (2, 3), 'Days 1-2': (2, 3), 'Day 2': (3, 6), 'Day 3': (4, 8), 'Day 4': (8, 16), 'Days 4-5': (10, 20),
          'Day 6': (12, 24), 'late addition': (12, 24), 'special scene': (12, 24), 'Chrysler (EX)': (12, 24)}
SKIP = ('Hospital map 159 actor',)
RESISTS = ('heat', 'frost', 'cyanide', 'acid', 'tranq')

SKINS = [  # name, price, kind (0 = Aya outfit area, 1 = character bundle), area / 0, bundle folder (pe_skins/<folder>), (map, slot) source
    ('Aya', 0, 0, 12, '', None), ('Aya: evening dress', 100, 0, 10, '', None), ('Aya: T-shirt', 100, 0, 13, '', None),
    ('Aya: long dress', 100, 0, 11, '', None), ("Aya: transformed", 400, 0, 14, '', None),
    ('Melissa', 400, 1, 0, 'melissa', (4, 3)), ('Eve', 400, 1, 0, 'eve', (23, 2)),
    ('Daniel', 250, 1, 0, 'daniel', (25, 3)), ('Maeda', 250, 1, 0, 'maeda', (25, 4)), ('Maya', 250, 1, 0, 'maya', (11, 2)),
    ('Chief Baker', 150, 1, 0, 'baker', (41, 3)), ('Daniel (gun drawn)', 150, 1, 0, 'daniel_gun', (94, 4)),
    ('Maeda (backpack)', 150, 1, 0, 'maeda_pack', (90, 2)),
    ("Aya's date", 50, 1, 0, 'date', (2, 2)), ('Policewoman', 50, 1, 0, 'policewoman', (48, 2)),
    ('Policewoman (cap)', 50, 1, 0, 'policewoman_cap', (43, 4)), ('Officer (moustache)', 50, 1, 0, 'officer', (52, 3)),
    ('Officer (cap)', 50, 1, 0, 'officer_cap', (1, 3)), ('NYPD (brown jacket)', 50, 1, 0, 'nypd_jacket', (41, 4)),
    ('NYPD (holster)', 50, 1, 0, 'nypd_holster', (41, 5)), ('Opera actress', 50, 1, 0, 'opera_actress', (49, 2)),
    ('Opera (doublet)', 50, 1, 0, 'opera_doublet', (49, 3)), ('Opera king', 50, 1, 0, 'opera_king', (49, 4)),
    ('Opera knight', 50, 1, 0, 'opera_knight', (49, 5)), ('Harlequin', 50, 1, 0, 'harlequin', (17, 1)),
    ('Usher', 50, 1, 0, 'usher', (2, 3)), ('Crew', 50, 1, 0, 'crew', (275, 3)),
]


def base_name(n):
    n = n.split(' (')[0]
    for suffix in (' part', ' form', ' larva', ' (offspring)'):
        if n.endswith(suffix): n = n[: -len(suffix)]
    return n


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    rows = json.loads(DRAFT.read_text())['enemies']
    creatures, lookup = {}, []
    for r in sorted(rows, key=lambda r: ORDER.index(r['first']) if r['first'] in ORDER else 99):
        if not r.get('name') or r['name'] in SKIP: continue
        ex = r['first'] == 'Chrysler (EX)'
        key = (base_name(r['name']), ex)
        exp = r['exp'] if isinstance(r['exp'], int) else 0
        better = key in creatures and creatures[key]['section'] == r['first'] and exp > creatures[key]['exp']
        if key not in creatures or better:            # show the first section's main block (most EXP)
            weak = sum(1 << i for i, k in enumerate(RESISTS) if k in r['weak'])
            strong = sum(1 << i for i, k in enumerate(RESISTS) if k in r['strong'])
            hp = r['hp'] if isinstance(r['hp'], int) else 0
            if better: hp = max(hp, creatures[key]['hp'])
            creatures[key] = dict(name=key[0], ex=ex, section=r['first'], hp=min(hp, 65535), defense=min(int(r['defense'] or 0), 65535) if isinstance(r['defense'], int) else 0,
                                  weak=weak, strong=strong, drop=r['drop'], steal=r['steal'], boss=r['role'] == 'boss', exp=exp)
        c = creatures[key]
        if c['section'] == r['first'] and isinstance(r['hp'], int):
            c['hp'] = max(c['hp'], min(r['hp'], 65535))   # bosses: the biggest part's HP (Sheeva's heads, not its 10-HP core)
        idx = list(creatures).index(key)
        for m in r['maps']:
            lookup.append((m, int(r['id'], 16), idx))
    lookup = sorted(set(lookup))
    L = ['/* Generated by psxrecomp-decomp-bridge tools/pe_assets/gen_collection_data.py from',
         ' * findings/data/pe-bestiary-draft-2026-10-19.json. Do not edit by hand. */',
         '#pragma once', '#include <stdint.h>', '',
         'typedef struct { const char *name; uint8_t ex, boss; uint8_t price_weak, price_loot; const char *section;',
         '                 uint16_t hp, defense; uint8_t weak, strong; const char *drop, *steal; } PeCreature;',
         'typedef struct { uint16_t map, id; uint8_t creature; } PeCreatureKey;',
         'typedef struct { const char *name; uint16_t price; uint8_t kind, area; const char *folder; } PeSkin;',
         '/* weak / strong bits: 1 heat, 2 frost, 4 cyanide, 8 acid, 16 tranq. Skin kind 0 = Aya outfit (area),',
         ' * 1 = character bundle in pe_skins/<folder>/ (built from the user\'s disc by tools/pe_assets/build_skin.py;',
         ' * shown as "soon" and not sold while its files are missing). */', '',
         '#define PE_CREATURES %d' % len(creatures), 'static const PeCreature g_pe_creatures[PE_CREATURES] = {']
    for c in creatures.values():
        pw, pl = PRICES.get(c['section'], (12, 24))
        L.append('    { %s, %d, %d, %d, %d, %s, %d, %d, %d, %d, %s, %s },' % (
            c_str(c['name']), c['ex'], c['boss'], pw, pl, c_str(c['section']), c['hp'], c['defense'], c['weak'], c['strong'], c_str(c['drop']), c_str(c['steal'])))
    L += ['};', '', '#define PE_CREATURE_KEYS %d' % len(lookup), 'static const PeCreatureKey g_pe_creature_keys[PE_CREATURE_KEYS] = {']
    for m, i, c in lookup: L.append('    { %d, 0x%04X, %d },' % (m, i, c))
    L += ['};', '', '#define PE_SKINS %d' % len(SKINS), 'static const PeSkin g_pe_skins[PE_SKINS] = {']
    for n, p, k, a, folder, _ in SKINS: L.append('    { %s, %d, %d, %d, %s },' % (c_str(n), p, k, a, c_str(folder)))
    L += ['};', '']
    OUT.write_text('\n'.join(L), encoding='utf-8')
    print(OUT, len(creatures), 'creatures', len(lookup), 'keys', len(SKINS), 'skins')


if __name__ == '__main__':
    main()
